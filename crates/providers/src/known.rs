//! Bundled catalog of known providers (snapshot of models.dev — the same
//! source opencode uses). Regenerate with `cargo run -p xtask -- gen-providers`.

use serde::Deserialize;

pub const SNAPSHOT_JSON: &str = include_str!("known/known_providers.json");

/// Wire protocol / adapter a provider routes to.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProtocolKind {
    /// Plain OpenAI Chat Completions wire at the given base URL.
    OpenAiCompat,
    /// Anthropic Messages wire.
    AnthropicCompat,
    /// Azure OpenAI (deployment URLs + `api-key` header).
    Azure,
    /// Google Gemini native `generateContent` (Generative Language API).
    GeminiNative,
    /// Vertex AI hosting Gemini models (project/location URL, OAuth bearer).
    VertexGemini,
    /// Vertex AI hosting Claude models (Anthropic wire on Vertex endpoints).
    VertexAnthropic,
    /// Amazon Bedrock Converse API (bearer token or SigV4).
    Bedrock,
    /// Cohere `/v2/chat` native schema.
    Cohere,
    /// GitLab Duo (ai-gateway URL, PAT).
    GitLabDuo,
    /// GitHub Copilot (device-flow OAuth + api.githubcopilot.com).
    Copilot,
    /// OpenAI-compatible wire behind an IBM IAM token pre-auth step.
    OpenAiCompatIbmIam,
    /// OpenAI-compatible wire behind an OAuth client-credentials pre-auth.
    OpenAiCompatOauthCc,
}

impl ProtocolKind {
    pub fn provider_type(&self) -> &'static str {
        match self {
            Self::OpenAiCompat => "openai-compatible",
            Self::AnthropicCompat => "anthropic-compatible",
            Self::Azure => "azure-openai",
            Self::GeminiNative => "google-gemini",
            Self::VertexGemini => "google-vertex-gemini",
            Self::VertexAnthropic => "google-vertex-anthropic",
            Self::Bedrock => "aws-bedrock",
            Self::Cohere => "cohere",
            Self::GitLabDuo => "gitlab-duo",
            Self::Copilot => "github-copilot",
            Self::OpenAiCompatIbmIam => "watsonx-iam",
            Self::OpenAiCompatOauthCc => "oauth-client-credentials",
        }
    }
}

#[derive(Debug, Clone, Deserialize)]
pub struct KnownEntry {
    pub id: String,
    #[serde(default)]
    pub name: String,
    #[serde(default)]
    pub npm: Option<String>,
    #[serde(default)]
    pub api: Option<String>,
    /// Every env var models.dev lists for the provider (docs/TUI display).
    #[serde(default)]
    pub env: Vec<String>,
    /// Subset of `env` (plus explicit overrides) that actually carries the
    /// credential. Regenerated by xtask; a legacy snapshot without the field
    /// is classified at load time by [`classify_key_envs`].
    #[serde(default)]
    pub key_envs: Vec<String>,
}

#[derive(Debug, Clone)]
pub struct ResolvedKnown {
    pub entry: KnownEntry,
    pub protocol: ProtocolKind,
    /// Effective base URL (catalog value, well-known fallback, or dynamic
    /// placeholder that the adapter resolves from env at call time).
    pub base_url: Option<String>,
    /// Env var names that carry the credential, in priority order.
    pub key_envs: Vec<String>,
    /// False for local runtimes (ollama/lmstudio/…) — no key needed.
    pub requires_key: bool,
}

/// Explicit credential env vars for entries the name heuristic cannot
/// classify reliably. `env` stays the display source of truth; these are
/// intersected with nothing — an override always wins.
const KEY_ENV_OVERRIDES: &[(&str, &[&str])] = &[
    ("azure", &["AZURE_API_KEY"]),
    (
        "azure-cognitive-services",
        &["AZURE_COGNITIVE_SERVICES_API_KEY"],
    ),
    ("cloudflare-workers-ai", &["CLOUDFLARE_API_KEY"]),
    ("cloudflare-ai-gateway", &["CLOUDFLARE_API_TOKEN"]),
    ("databricks", &["DATABRICKS_TOKEN"]),
    ("neon", &["NEON_AI_GATEWAY_TOKEN"]),
    ("snowflake-cortex", &["SNOWFLAKE_CORTEX_PAT"]),
    ("google-vertex", &["GOOGLE_APPLICATION_CREDENTIALS"]),
    (
        "google-vertex-anthropic",
        &["GOOGLE_APPLICATION_CREDENTIALS"],
    ),
    ("watsonx", &["WATSONX_AI_APIKEY"]),
    ("sap-ai-core", &["AICORE_SERVICE_KEY"]),
    ("github-copilot", &["GITHUB_TOKEN"]),
];

/// True when an env var name looks like it carries a secret.
///
/// Names are tokenized on `_`/non-alphanumerics and matched on whole tokens
/// (suffix `KEY`, contains `TOKEN`/`SECRET`/`PASSWORD`/`CREDENTIAL`, exact
/// `PAT`) so `AZURE_RESOURCE_NAME` is not mistaken for a key while
/// `WATSONX_AI_APIKEY` and `SNOWFLAKE_CORTEX_PAT` are.
pub fn is_secret_like_env_name(name: &str) -> bool {
    name.split(|c: char| !c.is_ascii_alphanumeric()).any(|tok| {
        let t = tok.to_ascii_uppercase();
        t.ends_with("KEY")
            || t.contains("TOKEN")
            || t.contains("SECRET")
            || t == "PAT"
            || t.contains("PASSWORD")
            || t.contains("CREDENTIAL")
    })
}

/// Select the credential-bearing names from a models.dev `env` list.
///
/// models.dev lists *all* env vars a provider reads, in arbitrary order
/// (`AZURE_RESOURCE_NAME` before `AZURE_API_KEY`), so using the raw list as
/// the key-hunt order turns a resource name into an "API key". This is the
/// single source of truth used both by the snapshot generator and as a
/// fallback for snapshots written before `key_envs` existed.
pub fn classify_key_envs(id: &str, env: &[String]) -> Vec<String> {
    if let Some((_, keys)) = KEY_ENV_OVERRIDES.iter().find(|(k, _)| *k == id) {
        return keys.iter().map(|s| (*s).to_string()).collect();
    }
    let matched: Vec<String> = env
        .iter()
        .filter(|name| is_secret_like_env_name(name))
        .cloned()
        .collect();
    if !matched.is_empty() {
        return matched;
    }
    // A single declared env var is the key even if the name is unusual;
    // multiple unclassifiable names must not all be tried as keys.
    if env.len() == 1 {
        env.to_vec()
    } else {
        Vec::new()
    }
}

#[derive(Debug, Clone, Deserialize, Default)]
pub struct KnownCatalog {
    #[serde(default)]
    pub snapshot_version: String,
    #[serde(default)]
    pub providers: Vec<KnownEntry>,
}

impl KnownCatalog {
    pub fn load() -> Self {
        serde_json::from_str(SNAPSHOT_JSON).unwrap_or_default()
    }

    /// Resolve protocol + effective settings for every entry, including the
    /// local-runtime fallbacks the catalog may not list yet.
    pub fn resolved(&self) -> Vec<ResolvedKnown> {
        let mut out: Vec<ResolvedKnown> = self.providers.iter().map(resolve_entry).collect();
        for (id, name, url) in LOCAL_RUNTIME_FALLBACKS {
            if out.iter().any(|r| r.entry.id == *id) {
                continue;
            }
            out.push(resolve_entry(&KnownEntry {
                id: (*id).to_string(),
                name: (*name).to_string(),
                npm: Some("@ai-sdk/openai-compatible".into()),
                api: Some((*url).to_string()),
                env: Vec::new(),
                key_envs: Vec::new(),
            }));
        }
        out
    }
}

