const LOCAL_IDS: &[&str] = &[
    "ollama",
    "lmstudio",
    "llamacpp",
    "atomic-chat",
    "vllm",
    "qvac",
    "localai",
];

/// Local runtimes the runner supports natively even when the catalog does not
/// list them. Plain-http localhost URLs, no credentials, OpenAI-compatible
/// wire — the README's local-provider table must match this list.
const LOCAL_RUNTIME_FALLBACKS: &[(&str, &str, &str)] = &[
    ("ollama", "Ollama", "http://localhost:11434/v1"),
    ("llamacpp", "llama.cpp", "http://localhost:8080/v1"),
    ("vllm", "vLLM", "http://localhost:8000/v1"),
    ("localai", "LocalAI", "http://localhost:8080/v1"),
];

pub fn resolve_entry(entry: &KnownEntry) -> ResolvedKnown {
    let protocol = id_override(&entry.id)
        .or_else(|| entry.npm.as_deref().and_then(npm_to_protocol))
        .unwrap_or(ProtocolKind::OpenAiCompat);

    // Catalog URLs sometimes carry `${ENV_VAR}` placeholders (Cloudflare,
    // Databricks, Infomaniak, Neon, Snowflake) — interpolate them now so the
    // provider gets a concrete, working URL. Missing vars drop the URL; the
    // provider then fails with the standard "needs an API URL" message
    // instead of sending requests to a literal `${...}` host.
    let mut api = entry.api.clone();
    if let Some(url) = &api {
        if matches!(protocol, ProtocolKind::OpenAiCompat) {
            // Routed providers append `/chat/completions` themselves; strip a
            // catalog URL that already includes it (e.g. `bailing`).
            api = Some(strip_chat_suffix(url));
        }
    }
    let base_url = api
        .and_then(|u| interpolate_env(&u).ok())
        .or_else(|| fallback_url(&entry.id).map(|s| s.to_string()));

    let requires_key = if LOCAL_IDS.contains(&entry.id.as_str()) {
        false
    } else {
        !entry.env.is_empty() || !matches!(protocol, ProtocolKind::OpenAiCompat)
    };

    // Prefer the generated field; classify legacy snapshots on load.
    let key_envs = if entry.key_envs.is_empty() {
        classify_key_envs(&entry.id, &entry.env)
    } else {
        entry.key_envs.clone()
    };

    ResolvedKnown {
        entry: entry.clone(),
        protocol,
        base_url,
        key_envs,
        requires_key,
    }
}

/// Remove a trailing `/chat/completions` from an OpenAI-compatible base URL.
fn strip_chat_suffix(url: &str) -> String {
    let trimmed = url.trim_end_matches('/');
    if let Some(rest) = trimmed.strip_suffix("/chat/completions") {
        rest.to_string()
    } else {
        url.to_string()
    }
}

/// Replace every `${VAR}` in `url` with its environment value. Returns the
/// names of any variables that are not set (or whose value is unsafe to
/// interpolate).
fn interpolate_env(url: &str) -> std::result::Result<String, Vec<String>> {
    let mut missing = Vec::new();
    let mut out = String::new();
    let mut rest = url;
    while let Some(start) = rest.find("${") {
        out.push_str(&rest[..start]);
        let after = &rest[start + 2..];
        let Some(end) = after.find('}') else {
            out.push_str(&rest[start..]);
            rest = "";
            break;
        };
        let var = &after[..end];
        match std::env::var(var)
            .ok()
            .and_then(|v| sanitize_base_url_component(&v))
        {
            Some(value) => out.push_str(&value),
            None => {
                // Unset *or* unsafe to embed — fail closed: the caller drops
                // the URL instead of building a surprising one.
                missing.push(var.to_string());
                out.push_str(&rest[start..start + 2 + end + 1]);
            }
        }
        rest = &after[end + 1..];
    }
    out.push_str(rest);
    if missing.is_empty() {
        Ok(out)
    } else {
        Err(missing)
    }
}

/// Reject env values that would change the URL's meaning when embedded
/// (path traversal, userinfo, spaces, embedded scheme/authority).
fn sanitize_base_url_component(value: &str) -> Option<String> {
    let unsafe_value = value.is_empty()
        || value.chars().any(|c| c.is_whitespace() || c.is_control())
        || value.contains("..")
        || value.contains('@')
        || value.contains('\\')
        || value.contains("//")
        || value.contains('?')
        || value.contains('#');
    (!unsafe_value).then(|| value.to_string())
}

/// Every known provider resolved and ready for registry insertion.
pub fn all_resolved() -> Vec<ResolvedKnown> {
    KnownCatalog::load().resolved()
}

